// Developer asset encoding only; original PNGs are never rewritten. Requires ImageMagick.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { createGame } from '../tests/helpers/game.js';
const run=promisify(execFile),root=new URL('../',import.meta.url),folder=new URL('assets/drivers/portraits/',root);
const {game}=createGame(),drivers=new Map(game.MASTER.drivers.map(d=>[d.id,d]));
const names=readdirSync(folder).filter(name=>/^d\d{3}\.png$/.test(name)).sort();
mkdirSync(new URL('webp/',folder),{recursive:true});
const code=name=>{const words=name.trim().split(/\s+/),clean=words.at(-1).normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-zA-Z]/g,'').toUpperCase();return(clean.slice(0,3)||'???').padEnd(3,'X');};
const entries=[];
for(const name of names){
 const id=name.slice(0,-4),driver=drivers.get(id);if(!driver)throw Error('Unbekannte Fahrer-ID: '+id);
 const input=new URL(name,folder),output=new URL(`webp/${id}.webp`,folder);
 await run('convert',[input.pathname,'-resize','640x800>','-quality','90',output.pathname]);
 const original=readFileSync(input),optimized=readFileSync(output);
 entries.push({id,code:code(driver.name),name:driver.name,source:`assets/drivers/portraits/${name}`,sourceSHA256:createHash('sha256').update(original).digest('hex'),src:`./assets/drivers/portraits/webp/${id}.webp`,bytes:optimized.length,sha256:createHash('sha256').update(optimized).digest('hex')});
}
writeFileSync(new URL('manifest.json',folder),JSON.stringify({version:1,entries},null,2)+'\n');
const data=Object.fromEntries(entries.map(({id,code,src})=>[id,{code,src}]));
writeFileSync(new URL('src/data/uploaded-portraits.js',root),'/* Uploaded art by immutable driver ID; generated by build:uploaded-portraits. */\n(()=>{const data='+JSON.stringify(data)+';globalThis.CGPUploadedPortraits=Object.freeze(Object.fromEntries(Object.entries(data).map(([id,p])=>[id,Object.freeze(p)])));})();\n');
console.log(`${entries.length} Porträts eingebunden: ${entries.reduce((sum,p)=>sum+p.bytes,0)} Bytes Spielgrafiken; Originale unverändert.`);
