import { readFileSync, writeFileSync } from "node:fs";
const reference = JSON.parse(readFileSync(new URL("../docs/race-duration/clean-reference.json", import.meta.url))),
  targetSeconds = 210, minLaps = 4, maxLaps = 12,
  overrides = { bahrain: 8 };
if (reference.tracks.length !== 22) throw Error("Alle 22 Strecken müssen vermessen sein.");
const tracks = {};
for (const track of reference.tracks) {
  const sample = track.keyboard,
    seconds = sample.referenceSeconds,
    start = sample.launchSeconds;
  if (sample.cleanLapSeconds.length !== 3 || !Number.isFinite(seconds) || seconds <= 0)
    throw Error(`Ungültige Referenz für ${track.id}`);
  const laps = overrides[track.id] ??
    Math.max(minLaps, Math.min(maxLaps, Math.round((targetSeconds - start) / seconds)));
  tracks[track.id] = {
    laps, referenceSeconds: seconds,
    estimatedSeconds: Math.round((start + laps * seconds) * 1000) / 1000,
  };
}
const settings = { version: 1, targetSeconds, minLaps, maxLaps, tracks },
  source = `// Generated by scripts/build-race-formats.js from documented clean reference laps.
// Stable race lengths, independent of player skill, restarts, traffic and save data.
(() => {
  "use strict";
  const A = (globalThis.CGPArcade = globalThis.CGPArcade || {}),
    settings = ${JSON.stringify(settings, null, 2)};
  for (const format of Object.values(settings.tracks)) Object.freeze(format);
  Object.freeze(settings.tracks);
  Object.freeze(settings);
  function get(id) {
    if (!Object.hasOwn(settings.tracks, id)) throw Error("Unbekanntes Rennformat.");
    return settings.tracks[id];
  }
  A.RaceFormats = Object.freeze({ settings, get });
})();
`,
  path = new URL("../src/data/race-formats.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== source) throw Error("Rennformate stimmen nicht mit den Referenzmessungen überein.");
} else writeFileSync(path, source);
